# -*- coding: utf-8 -*-
"""ch09_verify.py —— 卷 9 第 7 章：当检查工具说"全绿"

## 这一章要讲的事

一块板子画完，跑一遍 DRC（设计规则检查），报告说"违规 0 条" ——
**你就可以投板了吗？**

二代这块板子的亲身经历是：**不能。**

    2026-09-08  报告"HV 爬电 0、短路 0"，记为"电气门禁全过"
    2026-09-11  复核发现：那份"0"**不可信**
                真实基线是 HV 爬电 **133** 条、真短路 **5** 条

**从 0 到 133。** 而这两次读的是**同一块板**。

本章不讲"怎么修板"，讲**为什么判据会骗人**，以及**怎么让它骗不了人**。
这是本丛书反复遇到的那一类错：**工具报绿，产物是错的。**

## 本脚本做什么

① 把两份判据的结果并排放（哪些项少报、少报多少）
② 少报的机制之一：**一个对象违反多条，只报一条**（玩具模型，合成数据）
③ 少报的机制之二：**同一命令连跑两次，两个数**
④ ★★ 规则被**改哑**：注入已知违规，验证判据还响不响（本章核心）
⑤ 身份错位：重复 ID 让报告指错对象

⚠️ ② 和 ④ 是**玩具模型**（合成数据），用来演示机制；
   ①③⑤ 的数字全部来自设计文档的**实测记录**，逐条注明。

跑法：python code/ch09_verify.py
"""

import unicodedata


def pad(s, n):
    """按**显示宽度**补齐。

    ⚠️ `'%-24s' % '中文名'` 会排歪 —— `%` 数的是**字符数**，而终端里
       一个汉字占**两列**。本脚本的输出要印进书里，所以这里按列宽补。
    """
    return s + ' ' * max(0, n - sum(
        2 if unicodedata.east_asian_width(c) in 'WF' else 1 for c in s))

# ---- ① 两份判据的真实对照（来自设计文档 08 §10.1 / §10.3）----
#     口径：商业 DRC 的"报什么" vs 确定性几何扫描的"真实基线"
BASELINE = [
    ('HV 爬电（1.5mm，外层）', 72, 133, '商业 DRC', '确定性扫描'),
    ('致命短路',                2,   5, '商业 DRC', '确定性扫描'),
    ('0.15mm 普通间距',         0,  33, '商业 DRC', '确定性扫描'),
]

# ---- ③ 不可复现：同一条命令、同一块板，连跑两次（文档 08 §10.1 原文）----
RERUN = [67, 65]

# ---- ④ 规则改哑的正向对照（文档 08 §10.2 末尾，原文实测）----
INJECTED = 2      # 故意注入的 2 条外层违规
CAUGHT_BEFORE = 6 # 改规则前：命中 6（含注入的 2 条）
CAUGHT_AFTER = 0  # 加了一个条件后：命中 0
CAUGHT_REVERT = 6 # 回退后：又命中 6

# ---- ⑤ 身份错位（文档 08 §10.1 第 2 条 / §10.4）----
DUP_UUID_GROUPS = 71    # 重复的焊盘 UUID 组数
UUID_REISSUED = 287     # 重发的 UUID 个数
SHORTS_CONFIRMED = 5    # 重发后名字全对的真短路条数


# ---- 时间线（文档 08 的原记录，日期进正文 ⇒ 也必须从脚本里出来）----
TIMELINE = [
    ('2026-09-08', '跑一遍 DRC，报告"HV 爬电 0、短路 0"，记为"电气门禁全过"'),
    ('2026-09-11', '复核：那份"0"不可信 —— 真实基线是 133 / 5 / 33'),
]

# ---- 整改之后（文档 08 §10.3 的实测结果）----
#     ⚠️ 0.15mm 那一类在**两份文档里记的不一样**：文档 08 记「停在 17」，
#        文档 12 记「改出脚方向后降到 0」。两条不可能同时是当前状态。
#        本脚本**不判谁对** —— 那要去跑板文件；这里只把冲突摆出来。
AFTER_FIX = [
    ('HV 爬电（1.5mm，外层）', 133, 0,  '可解，已清零'),
    ('致命短路',                5,   0,  '可解，已清零'),
    ('0.15mm 普通间距',        33,  17,  '⚠️ 两份文档对不上，见下'),
]

# ---- ⑦ 两份文档、同一个 17 条、互相矛盾（本脚本不判谁对）----
CONFLICT = [
    ('文档 A', '停在 17 条',
     '判为"结构性不可解"：试了一种替代解法（把短桩换成打在焊盘里的小孔）后否掉'),
    ('文档 B', '降到 0 条',
     '换了另一种解法（出脚方向：斜穿改成垂直出脚）后全部消除'),
]


def main():
    print('=' * 74)
    print('⓪ 时间线：一个"全绿"是怎么被推翻的')
    print('=' * 74)
    for d, what in TIMELINE:
        print('  %s  %s' % (d, what))
    print()
    print('  ★ 两天，同一块板。中间没有改电路 ——')
    print('    改的是**"用什么判据去量"**。')

    print()
    print('=' * 74)
    print('① 同一块板，两份判据给出两个数')
    print('=' * 74)
    print('  %s %s %s %s'
          % (pad('项', 26), pad('商业 DRC', 12), pad('确定性扫描', 14), '差'))
    for name, drc, real, _a, _b in BASELINE:
        if drc == 0:
            gap = '**全漏**'
        else:
            gap = '漏 %d 条（%.2f×）' % (real - drc, real / float(drc))
        print('  %s %s %s %s'
              % (pad(name, 26), pad('%d 条' % drc, 12),
                 pad('%d 条' % real, 14), gap))
    print()
    print('  ★ 三行里有**两行是少报，一行是一条都没报**。')
    print('    而这三行出自**同一块板、同一份设计规则**——')
    print('    差别只在"用哪把尺子量"。')
    print()
    print('  ★★ 注意那个 0：它不是"漏了一点"，是**这一类问题整体看不见**。')
    print('     少报还能靠比例估回来；**整体看不见的一类，你连它存在都不知道。**')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('② 少报的机制之一：一个对象违反多条，只报一条')
    print('=' * 74)
    print('  ⚠️ 本节是**玩具模型**（合成数据），只演示机制，不是实测。')
    print()
    print('  商业 DRC 有一个默认关着的开关："Report all errors for tracks"。')
    print('  关着时，**每条走线只报它最差的那一条违规**。')
    print()
    print('  %s %s %s %s'
          % (pad('走线数', 12), pad('每条违反', 14), pad('真实违规', 14), '报告条数'))
    for n, m in ((72, 1), (36, 2), (24, 3), (16, 4)):
        truth = n * m
        print('  %s %s %s %s'
              % (pad('%d 条' % n, 12), pad('%d 条' % m, 14),
                 pad('%d 条' % truth, 14), '%d 条' % n))
    print()
    print('  ★ 报告条数 = **有问题的对象数**，而不是**问题数**。')
    print('    所以"报告 72 条"和"真实 133 条"并不矛盾：')
    print('    平均每个被报对象身上压着 **%.2f** 条违规。' % (133 / 72.0))
    print()
    print('  ★★ 文档里的实例更刺眼：某个器件的同一个焊盘在报告里出现 **0 次**,')
    print('     而同结构的另一个被报了 —— 因为前者的所在地同时违反了三条规则，')
    print('     报告只留了**最差的那一条**，另外两条连名字都没出现。')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('③ 少报的机制之二：同一命令连跑两次，两个数')
    print('=' * 74)
    print('  同一块板、同一条命令：')
    print()
    for i, n in enumerate(RERUN, 1):
        print('    第 %d 次运行：HV 爬电违规 **%d** 条' % (i, n))
    print()
    print('  ★ 差 %d 条。**一个不可复现的判据，本来就不能当判据用** ——' % abs(RERUN[0] - RERUN[1]))
    print('    因为你无法区分"这次真的更干净"和"这次恰好少报"。')
    print('    ⇒ 判据的第一条要求不是"准"，是**可复现**。')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('④ ★★ 规则被改哑 —— 本章的核心')
    print('=' * 74)
    print('  场景：爬电规则要给两个**自举轨**补上（它们对地摆到满输入电压）。')
    print('  改完再跑一遍，违规从 6 条变成 **0 条**。')
    print()
    print('  于是问题来了：**是规则把问题挡住了，还是规则死了？**')
    print('  两种情况下，报告都是"0"。')
    print()
    print('  判据：**先注入一条已知的违规，看规则还响不响。**')
    print()
    print('  %s %s %s' % (pad('规则状态', 32), pad('命中条数', 12), '结论'))
    print('  %s %s %s'
          % (pad('改动前（注入 %d 条已知违规）' % INJECTED, 32),
             pad('%d 条' % CAUGHT_BEFORE, 12), '✅ 规则在工作'))
    print('  %s %s %s'
          % (pad('改动后（报告说 0 条）', 32),
             pad('%d 条' % CAUGHT_AFTER, 12), '🔴 **规则死了，不是问题修好了**'))
    print('  %s %s %s'
          % (pad('回退改动', 32), pad('%d 条' % CAUGHT_REVERT, 12), '✅ 规则复活'))
    print()
    print('  ★★ 这三行就是**正向对照**。没有它，')
    print('     "改完变 0 了"**同时**对应两种完全相反的真相。')
    print()
    print('  ⚠️ 那个把规则改哑的条件是：给判据加一条 `B.Layer` 的层约束。')
    print('     它在 KiCad 的规则表达式里**恒为假** —— 于是整条规则恒不成立。')
    print('     而它**看起来**是在"把规则修得更精确"。')
    print()
    print('  ⇒ 改判据的人必须证明：**改完之后，判据对已知的错仍然会红。**')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('⑤ 身份错位：报告指着另一个对象')
    print('=' * 74)
    print('  还有一层更隐蔽的：报告把违规**贴到别的对象头上**。')
    print()
    print('    根因：板文件里有 **%d 组**焊盘 ID 重复' % DUP_UUID_GROUPS)
    print('          （生成器复制封装模板时没重发 ID）。')
    print('          DRC **按 ID 认对象** —— ID 撞了，违规就解析成另一个元件。')
    print('    症状：报告说"某焊盘与 36mm 外的另一个连接器间距 0.84mm"。')
    print('          看着像**工具的假象**，于是被长期豁免。')
    print()
    print('    实测：重发 **%d 个** ID 之后，同样的那 **%d 条**短路**名字全对**。'
          % (UUID_REISSUED, SHORTS_CONFIRMED))
    print()
    print('  ★★ "看着像工具的假象"是**最危险的豁免理由** ——')
    print('     因为它让"不查"显得有理有据。')
    print()
    print('  ★ 而且它污染了验证本身：当初用几何探针去"证伪"这些报告时，')
    print('    探针量的是**报告里写的那个对象** —— 也就是错的那个。')
    print('    ⇒ 既证伪不了，也证实不了。**用量具去核一个错的名字，等于没核。**')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('⑥ 于是判据要改成什么')
    print('=' * 74)
    print('  %s %s' % (pad('原来的判据', 32), '改成'))
    rows = [
        ('DRC 报 0 ⇒ 没有问题', '先注入已知违规，确认它还会报'),
        ('报告条数 = 问题数',   '报告条数 = 有问题的对象数（会少报）'),
        ('跑一次就下结论',       '连跑两次，先证明结果可复现'),
        ('报告指哪就查哪',       '先确认它指的对象是**真的那个**'),
        ('看着像假象就豁免',     '假象也要**用独立几何复核**，不靠观感'),
    ]
    for a, b in rows:
        print('  %s %s' % (pad(a, 32), b))
    print()
    print('  ★★★ 一句话：**"检查器没报错"和"没有问题"中间，')
    print('       隔着一个必须自己证明的前提 —— 检查器在工作。**')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('⑦ 整改之后 —— 以及一个"不可解"的结论被推翻')
    print('=' * 74)
    print('  %s %s %s %s'
          % (pad('项', 26), pad('整改前', 12), pad('整改后', 12), '结论'))
    for name, before, after, why in AFTER_FIX:
        print('  %s %s %s %s'
              % (pad(name, 26), pad('%d 条' % before, 12),
                 pad('%d 条' % after, 12), why))
    print()
    print('  ⚠️ 但第三行有个**真实的矛盾** —— 两份文档同时记着这 %d 条：' % 17)
    print()
    print('    %s %s' % (pad('记录', 14), '结果'))
    for who, res, why in CONFLICT:
        print('    %s %s' % (pad(who, 14), res))
        print('    %s %s' % (pad('', 14), why))
    print()
    print('  ★★ 两条记录**不可能同时是当前状态** —— 差的那 %d 条，' % 17)
    print('     要么已经消掉但有一处没回改，要么又被改回来了。')
    print('     **本脚本不判谁对**（那得去跑板文件），只把冲突摆出来。')
    print()
    print('  ★★★ 而这 %d 条真正值得记的是另一件事：' % 17)
    print('     文档 A 把它判成"**结构性不可解**"，并给了一句理由：')
    print('       「再怎么改扇出方式也只能做到"恰好零余量"」。')
    print('     它**试了一种**替代解法（把短桩换成打在焊盘里的小孔）并否掉了。')
    print()
    print('     ⇒ 而文档 B 换了**另一种**（改出脚方向：斜穿改成垂直出脚），过了。')
    print()
    print('  ★★★ 所以：**"不可解"这个判断，取决于你手上有哪些解法。**')
    print('       写"不可解"必须写清**在哪个解法集合里**不可解 ——')
    print('       否则它会在下一个人想到新解法的那一刻，变成一句错话。')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('自检 —— 本脚本引用的数字之间必须自洽')
    print('=' * 74)
    # ① 少报的方向必须一致：确定性扫描 >= 商业 DRC
    for name, drc, real, _a, _b in BASELINE:
        assert real >= drc, '① 方向反了：%s' % name
        print('  ✓ %-24s 真实 %3d ≥ 报告 %3d' % (name, real, drc))
    # ② 正向对照的三行必须构成"响 → 哑 → 响"
    assert CAUGHT_BEFORE > 0 and CAUGHT_AFTER == 0 and CAUGHT_REVERT > 0, \
        '② 正向对照不自洽'
    assert CAUGHT_BEFORE == CAUGHT_REVERT, '② 回退没回到原值'
    print('  ✓ 正向对照 %d → %d → %d（响 → 哑 → 响）'
          % (CAUGHT_BEFORE, CAUGHT_AFTER, CAUGHT_REVERT))
    # ③ 注入的违规必须**少于**命中数，否则"命中"里没包含注入的，对照不成立
    assert INJECTED < CAUGHT_BEFORE, '③ 注入数 ≥ 命中数：对照不成立'
    print('  ✓ 注入 %d 条 < 命中 %d 条（说明命中里含旧有违规）'
          % (INJECTED, CAUGHT_BEFORE))
    # ④ 重发 ID 之后的短路条数必须非零，否则"名字全对"是空的
    assert SHORTS_CONFIRMED > 0 and UUID_REISSUED > DUP_UUID_GROUPS, \
        '④ 身份错位那组数不自洽'
    print('  ✓ 重发 %d 个 ID（> 重复组数 %d），确认 %d 条短路'
          % (UUID_REISSUED, DUP_UUID_GROUPS, SHORTS_CONFIRMED))
    print()
    print('  ✅ 自检通过')
    print()
    print('=' * 74)
    print('口径：①③④⑤ 的数取自二代设计文档 08 的实测记录；')
    print('      ② 是合成数据的玩具模型，只演示机制。')
    print('      本脚本**不重跑 DRC** —— 那是板厂的封闭工具，本机没有。')
    print('=' * 74)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
