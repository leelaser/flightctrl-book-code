#!/usr/bin/env bash
# ch07_kconfig.sh —— 卷 7 第 4 章：内核配置里都有些什么
#
# 裁剪内核的第一步不是"关掉一些选项"，而是**先看清现在有什么**。
# 内核在编译时定下的每一件事都留在 `/proc/config.gz` 里（前提是开了
# CONFIG_IKCONFIG_PROC），这个脚本把那份配置**数一数、分分类**。
#
# 它回答三个问题：
#   ① 这份配置一共定了多少个符号，其中"编进去""编成模块""明确关掉"各多少？
#   ② 按子系统分，**带进来了多少东西**？（这才是"内核胖不胖"的答案）
#   ③ 编进去（=y）和编成模块（=m）在飞控上有什么区别？
#
# 跑法：bash code/ch07_kconfig.sh
#
# ★★ 口径声明：数出来的是**你这台机器**的配置。
#    各发行版默认配置差得很远（桌面版比服务器版胖得多），
#    所以**数字没有可比性，判读方法有**。
#    ⚠️ 真要把内核改小，得**重新编译**（源码 + 工具链 + 半小时起）——
#       那一步本机未必做得了（见脚本末尾的自检）。

set -u

CFG=""
if [ -r /proc/config.gz ]; then
    CFG=$(zcat /proc/config.gz)
    SRC=/proc/config.gz
elif [ -r "/boot/config-$(uname -r)" ]; then
    CFG=$(cat "/boot/config-$(uname -r)")
    SRC="/boot/config-$(uname -r)"
fi

if [ -z "$CFG" ]; then
    echo "读不到内核配置。"
    echo "  要看它，内核编译时得打开 CONFIG_IKCONFIG_PROC。"
    echo "  有的发行版用 /boot/config-\$(uname -r)（本脚本也认这个路径）。"
    exit 1
fi

echo "========================================================================"
echo "配置来源：$SRC"
echo "========================================================================"

# ---------------------------------------------------------------------------
echo
echo "① 这份配置的构成"
echo "========================================================================"
n_y=$(echo "$CFG" | grep -cE '^CONFIG_[A-Za-z0-9_]+=y$')
n_m=$(echo "$CFG" | grep -cE '^CONFIG_[A-Za-z0-9_]+=m$')
n_str=$(echo "$CFG" | grep -cE '^CONFIG_[A-Za-z0-9_]+="')
n_num=$(echo "$CFG" | grep -cE '^CONFIG_[A-Za-z0-9_]+=[0-9]')
n_no=$(echo "$CFG" | grep -cE '^# CONFIG_[A-Za-z0-9_]+ is not set$')
n_tot=$((n_y + n_m + n_str + n_num + n_no))

printf "  %-34s %6d\n" "编进内核（=y）"        "$n_y"
printf "  %-34s %6d\n" "编成模块（=m）"        "$n_m"
printf "  %-34s %6d\n" "字符串/数值型（=\"…\", =123）" "$((n_str + n_num))"
printf "  %-34s %6d\n" "**明确关掉**（is not set）" "$n_no"
printf "  %-34s %6d\n" "合计符号"              "$n_tot"
echo
echo "  ★★ 最后那两行是本章的第一个要点："
echo "     「关掉」也是**配置的一部分** —— 内核把「我明确不要什么」"
echo "     同样记了下来。所以裁剪内核 = 改这个文件，而不是「从零开始减」。"
echo
if [ "$n_m" -gt 0 ]; then
    echo "  这台机器 =y : =m = $n_y : $n_m"
    if [ "$n_y" -gt $((n_m * 20)) ]; then
        echo "    ⇒ 绝大多数功能**直接编进了内核**（=y）。"
        echo "      飞控常这么选：没有模块加载步骤 ⇒ 启动路径更短、更可预测。"
    fi
else
    echo "  这台机器一个模块都没有（=m 为 0）—— 全部编进内核。"
fi

# ---------------------------------------------------------------------------
echo
echo "② 按子系统数一数：带进来了多少东西"
echo "========================================================================"
echo "  （只统计 =y，即**真正占着内核镜像**的那些）"
echo
printf "  %-28s %6s  %s\n" "子系统" "=y 项数" "它在内核里的样子"
# ⚠️ 分组表用 `|` 分隔，**不能用 `:`** —— 第一版写成 "USB[_:].*:USB（…）"，
#    而 `${g%%:*}` 会在**字符类里的那个冒号**上截断，pat 变成 `USB[`，
#    grep 当场报 "Unmatched ["。分隔符绝不能出现在模式自身里。
#    这里干脆只用**前缀**匹配（CONFIG_USB 能覆盖 CONFIG_USB_*），不需要字符类。
count() { echo "$CFG" | grep -cE "^CONFIG_$1.*=y$" || true; }
for g in \
    "USB|USB（主机/设备/各类外设）" \
    "NET_|网络协议栈与驱动" \
    "SND|音频（ALSA）" \
    "DRM|显卡（DRM）" \
    "FB|帧缓冲（老式显示）" \
    "FS_|各种文件系统" \
    "SCSI|SCSI 子系统" \
    "MMC|SD/eMMC" \
    "MTD|原始 Flash（NOR/NAND）" \
    "I2C|I2C 总线" \
    "SPI|SPI 总线" \
    "CAN|CAN 总线（飞控常用）" \
    "INPUT|输入设备（键鼠/触摸）" \
    "HID|人机接口设备" \
    "WLAN|无线网络" \
    "BT|蓝牙" \
    "KVM|虚拟化" \
    "CRYPTO|加密算法" \
    "SOUND|声音子系统" \
    "MEDIA|媒体/摄像头" \
    ; do
    pat=${g%%|*}; desc=${g##*|}
    n=$(count "$pat")
    if [ "${n:-0}" -gt 0 ]; then
        printf "  %-28s %6d  %s\n" "$desc" "$n" ""
    fi
done

# ---------------------------------------------------------------------------
echo
echo "========================================================================"
echo "③ =y 和 =m 在飞控上有什么区别"
echo "========================================================================"
echo
echo "  —— 现在加载着的模块（/proc/modules）——"
if [ -r /proc/modules ]; then
    nm=$(wc -l < /proc/modules)
    echo "    已加载模块数：$nm"
    if [ "$nm" -eq 0 ]; then
        echo "    ⇒ 一个模块都没加载。所有功能在启动时就都在内核里了。"
    fi
fi
echo
echo "  —— 模块目录（/lib/modules/\$(uname -r)）——"
MODDIR="/lib/modules/$(uname -r)"
if [ -d "$MODDIR" ]; then
    kn=$(find "$MODDIR/kernel" -name '*.ko*' 2>/dev/null | wc -l)
    du=$(du -sh "$MODDIR" 2>/dev/null | cut -f1)
    echo "    目录：$MODDIR"
    echo "    .ko 模块文件数：$kn      整个目录占用：${du:-未知}"
else
    echo "    没有 $MODDIR（连模块目录都没有 ⇒ 只能全靠 =y）"
fi

cat <<'TXT'

  —— 三行的取舍 ——
     =y  编进内核   启动时就在内存里，**不需要加载步骤**；
                    代价是内核镜像大、所有代码常驻内存
     =m  编成模块   用到才加载，省内存、省镜像；
                    代价是多一步（加载），且依赖根文件系统就绪
     不编          完全不进内核：省镜像、**省启动时的探测时间与失败概率**

  ★★ 飞控上的常见取向是**尽量 =y，但只编真要用的**：
     · 要 =y，因为"启动路径越短越可预测"（见第 3 章：探测失败要等超时）
     · 只编真要用的，因为**每个编进去的驱动都在消耗启动时间和失败概率**
TXT

# ---------------------------------------------------------------------------
echo
echo "========================================================================"
echo "④ 该关什么：从上面的数字到行动"
echo "========================================================================"
echo
echo "  判据很简单 —— 对上面 ② 里数出来的每一类问三个问题："
echo "    1. 这块板子上**有这个硬件吗**？（没有 ⇒ 关）"
echo "    2. 就算有，**飞控用得到吗**？（用不到 ⇒ 关）"
echo "    3. 关掉之后**有没有别的东西依赖它**？（有 ⇒ 一起处理）"
echo
echo "  第 3 个问题是裁剪里唯一的陷阱：内核选项之间有依赖，"
echo "  关掉一个，依赖它的那些会跟着消失或变得不可选 ——"
echo "  这也是为什么改配置要用 \`make menuconfig\` 之类**能显示依赖**的工具，"
echo "  而不是直接编辑 .config。"

# ---------------------------------------------------------------------------
echo
echo "========================================================================"
echo "⑤ 本机能不能真的裁一次内核？"
echo "========================================================================"
echo
if [ -d "/lib/modules/$(uname -r)/build" ]; then
    echo "  /lib/modules/$(uname -r)/build 存在 ⇒ 有内核头文件，可以编外部模块。"
else
    echo "  /lib/modules/$(uname -r)/build **不存在** ⇒ 没有内核头文件。"
    echo "    · 编不了外部模块（第 7 章的驱动实验会用到这一点）"
    echo "    · 也编不了内核本身"
    echo "  ⇒ 这一章只做**读配置、数配置、判读**——这些全部可复现。"
    echo "    真要裁一次，需要：内核源码 + 交叉工具链 + 半小时起的编译时间。"
    echo "    （方法不变：改配置 → 编译 → 比 size 与 dmesg，见第 3 章。）"
fi

echo
echo "========================================================================"
echo "读取完成（只读不写）。"
echo "========================================================================"
