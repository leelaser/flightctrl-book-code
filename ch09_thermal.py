# -*- coding: utf-8 -*-
"""ch09_thermal.py —— 卷 9 第 8 章：从"离够远"到"能不能标定"

## 这一章要讲的事

传感器旁边有个热源（恒温加热件）。**规则该怎么写？**

    直觉写法：**"加热件离磁力计 ≥ 15mm"**
    实际结果：在全板尺寸下，**这条规则无处可放** ——
              而另一条硬规则（加热器要铺满）就贴在旁边。

两条硬规则**不可同时成立**。于是必须**放弃一条**。
而放弃哪一条，取决于一个问题：

    **"15mm"这个数，到底在保护什么？**

## 本脚本把那个"到底在保护什么"算出来

① 距离买到了什么 —— 梯度随距离**连续**衰减，**没有"过线才安全"的台阶**
   （⚠️ 顺带核出：文档正文说"按 1/r"，但它自己给的两点反解是 r^-0.39）
② 真正决定梯度的是**热流路径**（R = 厚度 / 导热系数 / 面积）
③ 磁场随距离按 1/d² 衰减 —— 这一条才是"距离"真正在管的事
④ 三片传感器与热源的距离差 3.8 倍 ⇒ **必须逐片独立标定**

## 结论（一句话）

**规范该管的不是"距离够不够远"，而是"梯度是否稳定可标定"。**

跑法：python code/ch09_thermal.py
"""

import math
import unicodedata


def pad(s, n):
    """按显示宽度补齐（汉字占两列）。"""
    return s + ' ' * max(0, n - sum(
        2 if unicodedata.east_asian_width(c) in 'WF' else 1 for c in s))


# ---- ① 梯度随距离（文档 09 §2：芯片内 3mm 边长的温差）----
#     (距热源 mm, 温差下限 K, 温差上限 K)
GRAD = [
    (1.43, 1.8, 7.0),
    (5.00, 1.1, 4.3),
]

# ---- ② 热流路径的热阻 R = t / (k·A)（文档 09 §2）----
FR4_T = 0.2e-3      # 焊盘到内层平面之间的介质厚 m
FR4_K = 0.3         # FR4 导热系数 W/(m·K)
PAD_AREAS = [2.0, 10.0]     # 焊盘面积 mm²

# ---- ③ 磁场随距离 B ∝ 1/d²（文档 09 §5）----
B_AT_5MM = 0.7      # 5 mm 处的磁感应强度 µT（≈ 加热电流的贡献）
D_NEAR, D_FAR = 5.0, 15.0
GEO_TOTAL = 50.0    # 地磁总场 0.5 Gauss = 50 µT
GEO_HORIZ = 30.0    # 地磁水平分量典型值 µT（航向只受水平分量影响）

# ---- ④ 三片传感器与热源的距离（文档 09 §4）----
IMU_DIST = [2.60, 1.43, 5.41]

# ---- ⑤ 一条硬规则：加热件焊盘必须用盘中孔接入平面（文档 09 §2）----
#     这是"唯一能真正摊平梯度"的手段 —— 注意理由不是"更导热"，
#     而是"孔可以打进焊盘里"（见第 9 章）


def main():
    print('=' * 74)
    print('① ">= 15mm" 这条规则，到底买到了什么')
    print('=' * 74)
    print('  温度梯度在内层平面上径向扩散。文档给的是两个**实测点**')
    print('  （芯片内 3mm 边长的温差）：')
    print()
    print('  %s %s %s' % (pad('距热源', 12), pad('温差下限', 12), '温差上限'))
    for d, lo, hi in GRAD:
        print('  %s %s %s'
              % (pad('%.2f mm' % d, 12), pad('%.1f K' % lo, 12), '%.1f K' % hi))
    print()
    imp_lo = 1 - GRAD[1][1] / GRAD[0][1]
    imp_hi = 1 - GRAD[1][2] / GRAD[0][2]
    print('  从 %.2f mm 拉到 %.2f mm：' % (GRAD[0][0], GRAD[1][0]))
    print('    下限 %.1f K → %.1f K，改善 **%.0f%%**'
          % (GRAD[0][1], GRAD[1][1], imp_lo * 100))
    print('    上限 %.1f K → %.1f K，改善 **%.0f%%**'
          % (GRAD[0][2], GRAD[1][2], imp_hi * 100))
    print()
    print('  ★★ 距离翻了 %.1f 倍，改善只有 **%.0f%%** 左右。'
          % (GRAD[1][0] / GRAD[0][0], imp_lo * 100))
    print()
    # ★ 口径提示：文档正文写"按 1/r 衰减"，但**它自己给的两个点对不上 1/r**。
    #   反解衰减指数：ΔT ∝ r^-n  ⇒  n = ln(比值) / ln(距离比)
    n_impl = (math.log(GRAD[1][1] / GRAD[0][1])
              / math.log(GRAD[0][0] / GRAD[1][0]))
    print('  ⚠️ 口径提示：文档正文说梯度"按 1/r 衰减"，')
    print('     但**它自己给的两个点反解出来是 r^-%.2f**（不是 r^-1）。' % n_impl)
    print('     ⇒ 本脚本按**实测点**算改善幅度，不套那个函数形式。')
    print()
    print('  ★★★ 而这一点是本章的关键：')
    print('       **不存在"过线才安全"的台阶。**')
    print('       实测点之间的衰减是**连续**的 —— 挪远一点就少一点，')
    print('       挪到任何位置都**没有"到此为止"的拐点**。')
    print('       （注意：这一条**不依赖**上面那个函数形式 ——')
    print('         r^-0.4 和 r^-1 都是平滑的，**都没有台阶**。）')
    print()
    print('  ⇒ 所以 ">= 15mm" 这个门槛数，**不是从物理里推导出来的**，')
    print('    它是"再远就放不下了"和"再近就太糟"之间**人为划的一刀**。')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('② 那什么才真正决定梯度 —— 热流路径')
    print('=' * 74)
    print('  热量要从焊盘进到内层平面，得**穿过中间的介质**：')
    print()
    print('    R = 厚度 / (导热系数 × 面积)')
    print()
    print('  介质厚 %.1f mm、FR4 导热系数 ≈ %.1f W/(m·K)：' % (FR4_T * 1e3, FR4_K))
    print()
    print('  %s %s %s' % (pad('焊盘面积', 12), pad('热阻', 14), '含义'))
    for a in PAD_AREAS:
        r = FR4_T / (FR4_K * a * 1e-6)
        note = ('热**进不去**平面' if r > 200 else '热进得去')
        print('  %s %s %s'
              % (pad('%.0f mm²' % a, 12), pad('%.0f K/W' % r, 14), note))
    print()
    print('  ★★ 面积差 %.0f 倍，热阻也差 %.0f 倍 —— 热阻 **∝ 1/面积**。'
          % (PAD_AREAS[1] / PAD_AREAS[0], PAD_AREAS[1] / PAD_AREAS[0]))
    print()
    print('  ★★★ 这条才是要害：**热进不去平面，就只能靠窄走线局部散 ——')
    print('       而局部散的结果是"近场梯度反而更陡"。**')
    print()
    print('  ⇒ 所以"热源离得远不远"**不是源头**，')
    print('     "热能不能被摊平"才是。而摊平靠的是**把热导进平面**，')
    print('     不是把热源挪开。')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('③ 距离真正在管的那件事：磁场按 1/d² 衰减')
    print('=' * 74)
    print('  **热**要靠标定吃掉的，而**磁场**是另一回事 ——')
    print('  载流导体的磁场按 **1/d²** 衰减，这一条确实"越远越好"，而且衰减更快：')
    print()
    print('  %s %s %s' % (pad('距离', 12), pad('磁感应强度', 14), '相对地磁'))
    for d in (D_NEAR, D_FAR):
        b = B_AT_5MM * (D_NEAR / d) ** 2
        print('  %s %s %s'
              % (pad('%.0f mm' % d, 12), pad('%.3f µT' % b, 14),
                 '%.1f%%（对水平分量）' % (b / GEO_HORIZ * 100)))
    print()
    b5 = B_AT_5MM
    b15 = B_AT_5MM * (D_NEAR / D_FAR) ** 2
    err = math.degrees(math.atan(b5 / GEO_HORIZ))
    print('  地磁总场 %.0f µT（0.5 Gauss），水平分量典型 %.0f µT。'
          % (GEO_TOTAL, GEO_HORIZ))
    print('  ⇒ 在 %.0f mm 处，扰动占水平分量的 **%.1f%%**' % (D_NEAR, b5 / GEO_HORIZ * 100))
    print('     对应航向误差 ≈ arctan(%.1f/%.0f) = **%.1f°**' % (b5, GEO_HORIZ, err))
    print('  ⇒ 在 %.0f mm 处只剩 **%.3f µT** —— 低于 0.1 µT。' % (D_FAR, b15))
    print()
    print('  ★★ 所以"距离"这个判据**是有道理的 —— 但它管的是磁场，不是热**。')
    print('     把同一条距离要求套到**热**上，就套错了对象。')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('④ 三片传感器不在同一个环境里')
    print('=' * 74)
    print('  三片传感器到热源的距离分别是：')
    print()
    for i, d in enumerate(IMU_DIST, 1):
        print('    第 %d 片：**%.2f mm**' % (i, d))
    print()
    near, far = min(IMU_DIST), max(IMU_DIST)
    print('  最近 %.2f mm、最远 %.2f mm —— 距离相差 **%.1f 倍**。' % (near, far, far / near))
    print()
    print('  受热影响差多少，取决于用哪种衰减模型：')
    print('    · 按 r^-1（文档正文的说法）  ⇒ **%.1f 倍**' % (far / near))
    print('    · 按 r^-%.2f（实测点反解的） ⇒ **%.1f 倍**'
          % (n_impl, (far / near) ** n_impl))
    print()
    print('  ★★★ 注意：**这两个数差了一倍多，但结论完全一样** ——')
    print('       无论用哪个模型，三片的热环境都**显著不同**，')
    print('       补偿系数必然不同 ⇒ **必须逐片独立标定。**')
    print()
    print('  ★★ 这正是"结论对模型不敏感"的典型：')
    print('     当一条结论在**最乐观和最悲观两种模型下都成立**时，')
    print('     你不需要再争论该用哪个模型 —— **可以直接下结论。**')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('⑤ 于是判据改写')
    print('=' * 74)
    print('  %s %s' % (pad('原来的判据', 30), '改成'))
    rows = [
        ('热源离传感器 ≥ 15mm',  '梯度是否**稳定可标定**'),
        ('把热源挪远',            '把热**导进内层平面**（唯一的摊平手段）'),
        ('三片共用一份补偿',      '**逐片独立**标定（距离差 3.8 倍）'),
        ('"越远越好"',            '区分：**热**可标定、**磁场**才要距离'),
    ]
    for a, b in rows:
        print('  %s %s' % (pad(a, 30), b))
    print()
    print('  ★★★ 一句话：**"距离够不够远"是个没法验证的判据；')
    print('       "梯度是否稳定可标定"是个可以验证的判据。**')
    print()
    print('  ⚠️ 而且这条改写**不损失安全性** —— 它只是把一条')
    print('     "做不到、说不清、也没法验"的规则，')
    print('     换成了"做得到、说得清、能验收"的规则。')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('自检 —— 算式必须复现文档里的实测数与结论')
    print('=' * 74)
    # ① 改善幅度必须落在文档说的"约 30~40%"
    assert 0.30 <= imp_lo <= 0.45, '① 下限改善幅度不在文档区间'
    assert 0.30 <= imp_hi <= 0.45, '① 上限改善幅度不在文档区间'
    print('  ✓ 改善 %.0f%% / %.0f%%（文档记"约 30~40%%"）'
          % (imp_lo * 100, imp_hi * 100))
    # ② 热阻必须复现 333 / 67 K/W
    r2 = FR4_T / (FR4_K * 2.0e-6)
    r10 = FR4_T / (FR4_K * 10.0e-6)
    assert abs(r2 - 333) < 1, '② 2mm² 热阻对不上'
    assert abs(r10 - 67) < 1, '② 10mm² 热阻对不上'
    print('  ✓ 热阻 %.0f / %.0f K/W（文档记 333 / 67）' % (r2, r10))
    # ③ 15mm 处必须低于 0.1µT
    assert b15 < 0.1, '③ 15mm 处没降到 0.1µT 以下'
    print('  ✓ %.0f mm 处 %.3f µT（文档记"< 0.1 µT"）' % (D_FAR, b15))
    # ④ 5mm 处的占比必须落在文档说的 2~3%
    pct = b5 / GEO_HORIZ * 100
    assert 2.0 <= pct <= 3.0, '④ 占比不在文档说的 2~3%'
    print('  ✓ 5 mm 处占水平分量 %.1f%%（文档记 2~3%%）' % pct)
    # ⑤ 距离必须真的差 3 倍以上，否则"逐片标定"这条结论不成立
    assert far / near > 3.0, '⑤ 三片距离差不够，逐片标定的理由不成立'
    print('  ✓ 三片距离 %.2f / %.2f mm，相差 %.1f 倍' % (near, far, far / near))
    # ⑥ 趋势方向：距离增加 ⇒ 梯度下降、磁场下降（两个方向都不能反）
    assert GRAD[1][1] < GRAD[0][1] and GRAD[1][2] < GRAD[0][2], '⑥ 梯度方向反了'
    assert b15 < b5, '⑥ 磁场方向反了'
    print('  ✓ 距离↑ ⇒ 梯度↓ 且磁场↓（两个方向都对）')
    print()
    print('  ✅ 自检通过')
    print()
    print('=' * 74)
    print('口径：梯度实测值、介质厚、导热系数、磁场与距离均取自二代设计文档 09；')
    print('      热阻与磁感应强度由本脚本按 R=t/(kA) 与 B∝1/d² 复算。')
    print('      **本机没有这块板，也没有实测** —— 这里复算的是文档的推论链。')
    print('=' * 74)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
