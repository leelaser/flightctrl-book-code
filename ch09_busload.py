# -*- coding: utf-8 -*-
"""ch09_busload.py —— 卷 9 第 3 章：总线够不够用，是可以**算**的

## 为什么值得单独做一件事

"三颗 IMU 能不能挂在同一条 SPI 上？"——这个问题常常靠"试试看"回答。
但它其实**能算**：

    单次采样要传多少 bit  ×  每秒采多少次  =  这条传感器要占多少带宽

把挂在这条总线上的所有设备加起来，和总线的**理论容量**一比，
就知道余量有多少。

本脚本把二代（LeeFCS）设计文档里那次核算重做一遍。它给出的结论是
**"共享总线余量充裕，不需要为每颗 IMU 单独一条"** ——
而这条结论**推翻了"冗余就该物理隔离"的直觉**。

## 算法只有三行

    bit/秒 = 速率(Hz) × 每次字节数 × 8
    利用率 = Σ bit/秒 ÷ 总线时钟
    判据：利用率低 ⇒ 共享可行

⚠️ 口径：这是**理论带宽**。真实总线还有 CS 切换间隙、命令字、
   以及最要紧的——**多设备共享时的仲裁**。所以脚本里按文档的做法
   把单次传输**按 100 bit 估**（含地址字节与切换间隙），
   并在结论里明说这是**保守估计**。

跑法：python code/ch09_busload.py
"""


# (设备, 采样率 Hz, 说明)
LOAD = [
    ('主 IMU（惯性测量单元）',        8000, '8 kHz 姿态环主传感器'),
    ('冗余 IMU 的加速度计',           1600, '双传感器之一'),
    ('冗余 IMU 的陀螺仪',             2000, '双传感器之二'),
]
BITS_PER_XFER = 100        # 地址 1B + 数据 6B ≈ 56~80 bit，按 100 bit 保守估
BUS_MHZ = [10, 20, 24]     # 三档 SPI 时钟


def main():
    print('=' * 74)
    print('① 每颗传感器要占多少带宽')
    print('=' * 74)
    print('  单次采样按 **%d bit** 估（含地址字节与片选切换间隙）'
          % BITS_PER_XFER)
    print()
    print('  %-24s %-10s %-12s %s' % ('设备', '采样率', '带宽', '说明'))
    total = 0
    for name, rate, why in LOAD:
        bps = rate * BITS_PER_XFER
        total += bps
        print('  %-24s %-10s %-12s %s'
              % (name, '%d Hz' % rate, '%.0f kbps' % (bps / 1000.0), why))
    print('  %-24s %-10s %-12s %s' % ('合计', '', '%.0f kbps' % (total / 1000.0), ''))

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('② 挂在同一条总线上，余量还剩多少')
    print('=' * 74)
    print('  %-14s %-16s %-12s %-10s %s'
          % ('总线时钟', '理论容量', '占用率', '余量', '判断'))
    for mhz in BUS_MHZ:
        cap = mhz * 1e6
        util = total / cap
        verdict = '余量充裕' if util < 0.2 else ('偏紧' if util < 0.5 else '不可行')
        # ★ "余量"要单独印出来：正文里说的是"余量有 94%"，
        #   而那是 100% 减去占用率 —— **工具不印，正文里的数就没处核**。
        #   （第一版只印占用率，于是正文那句 94% 成了"脚本里找不到的数"。）
        print('  %-14s %-16s %-12s %-10s %s'
              % ('%d MHz' % mhz, '%.1f Mbps' % (cap / 1e6),
                 '%.1f%%' % (util * 100), '%.0f%%' % ((1 - util) * 100),
                 verdict))
    print()
    print('  ★★ 结论：**共享总线余量充裕** —— 不需要为每颗 IMU 单独一条。')
    print('     这条结论推翻了"冗余就该物理隔离"的直觉：')
    print('     隔离有很多层（电源、中断、总线…），')
    print('     **总线这一层的代价（引脚数、走线、连接器）最贵，而它恰恰最不必要。**')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('③ 那"隔离"到底该做在哪一层')
    print('=' * 74)
    print('  这是本章真正要讲的东西 —— **余度分层**。从下往上是：')
    print()
    rows = [
        ('① 电源域',   '每颗 IMU 独立 LDO',        '一颗坏了不拖累别颗'),
        ('② 中断线',   '每颗 IMU 独立的 DRDY',      '一颗的总线卡住，别颗仍能通知'),
        ('③ 总线',     '可共享（本条已算过）',       '带宽余量大，隔离代价最贵'),
        ('④ 软件',     '三取二表决 + 故障降级',      '前三层都失效时的最后兜底'),
    ]
    print('  %-12s %-26s %s' % ('层', '做法', '为什么是这一层'))
    for a, b, c in rows:
        print('  %-12s %-26s %s' % (a, b, c))
    print()
    print('  ★★ 判据是"**任何一层失效，上一层兜底**"。')
    print('     所以问题不是"要不要隔离"，而是"**在哪一层隔离最划算**"——')
    print('     牺牲掉最贵的那一层（总线），把预算花在最便宜又最有效的层上。')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('④ 算一算：三颗 IMU 如果全独立走线，代价是什么')
    print('=' * 74)
    per_imu_pins = 4        # SCK / MOSI / MISO / CS
    n = 3
    print('  每颗 IMU 独占一条 SPI 需要 %d 根信号线（SCK/MOSI/MISO/CS）' % per_imu_pins)
    print('  %d 颗全独立：%d 根' % (n, per_imu_pins * n))
    print('  共享一条：  %d 根 + %d 根片选 = %d 根'
          % (per_imu_pins - 1, n, (per_imu_pins - 1) + n))
    print()
    print('  ★ 省下来的是**连接器引脚** —— 而连接器的引脚数直接决定')
    print('    板子能做多小、堆叠能不能插得进去。这就是"总线隔离最贵"的具体含义。')

    print()
    print('=' * 74)
    print('口径：以上是**理论带宽**。真实总线还有仲裁开销，')
    print('      所以单次传输按 %d bit 保守估（不是按实际字节数）。' % BITS_PER_XFER)
    print('=' * 74)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
