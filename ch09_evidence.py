# -*- coding: utf-8 -*-
"""ch09_evidence.py —— 卷 9 第 9 章：六个答案，挑哪一个

## 这一章要讲的事

为了一个数（"一个过孔的热阻是多少"），查了五份来源，得到：

    70 / 150 / 162.8 / 192 / 407     （单位 K/W）

**同一个几何、六倍离散。** 这时候该怎么办？

最常见的做法是"挑一个顺手的" —— 而文档里那句话是：

    **"不许从中挑一个顺手的用"**

## 本章给的是排序证据的判据

不是"哪个来源更权威"，而是：

    **这个结论依赖哪些不确定的东西？依赖得越少，越可信。**

于是本章把三件事按"依赖度"排开：

① 五份来源的离散               —— 依赖模型假设、镀层、边界条件（**最不可信**）
② "Type VII 好 4~8 倍"          —— 依赖"Type VII = 铜"这个**未经核实的等同**（错就错在这）
③ **几何上限**：盘太小、塞不下孔 —— **只依赖三个量的实测**（**最可信**）

⇒ ③ 把整条路判死了，而它**不依赖任何有争议的常数**。

跑法：python code/ch09_evidence.py
"""

import unicodedata


def pad(s, n):
    """按显示宽度补齐（汉字占两列）。"""
    return s + ' ' * max(0, n - sum(
        2 if unicodedata.east_asian_width(c) in 'WF' else 1 for c in s))


# ---- ① 同一个量、五份来源（文档 28 §3）----
#     (来源, 值 K/W, 级别)
#     级别：A 一手原文 / B 检索引到标准号 / C 二手 / D 本机自算
SOURCES = [
    ('本机一阶模型',      162.8, 'D'),
    ('引 IPC-2221B',       70.0, 'B'),
    ('引 IPC-2152 附录B', 150.0, 'B'),
    ('板厂公开表',        192.0, 'C'),
    ('在线计算器',        407.0, 'C'),
]

# ---- ② "类型号 ≠ 导热能力"（文档 21 §Q12 / 28 §3bis）----
K_COPPER = 385.0        # 纯铜导热系数 W/(m·K)
K_PASTE = 8.0           # 厂家给的"铜浆"导热系数 W/(m·K) —— 名字里有"铜"
R_BARE_04 = 124.5       # Ø0.40 裸孔单孔热阻 K/W
R_FILL_04 = 115.5       # 同孔径 + 铜浆塞孔 K/W（孔壁铜 ∥ 孔芯）

# ---- ③ 几何上限：盘太小，塞不下孔（文档 28 §9.3）----
PAD_W, PAD_H = 1.725, 2.235     # 板上实测的散热盘尺寸 mm
VIA_D, VIA_PAD = 0.4, 0.8       # 孔径 / 盘径 mm（JLC 口径）
EDGE_MIN = 0.2                  # 孔到盘边最小距离 mm
REQUIRED_HOLES = 16             # 规范要求的孔数（"每盘 ≥16 孔"）
DOC_HOLES = 2                   # 文档记录的盘内几何上限（它自己那套排法）

# ---- ④ 出口：把散热口挪到"本网铜岛"（文档 28 §9.4 / §10.3）----
R_IN_PAD = 66.1         # 盘内 2 孔并联 K/W（几何上限）
R_IN_ISLAND = 4.4       # 岛内 30 孔并联 K/W
ISLAND_HOLES = 30

# ---- ⑤ 模型唯一的独立校验（文档 28 §10.2）----
#     厂商实测的"铺开铜饱和点"区间，与模型给的饱和尺度对照
AN821_LO, AN821_HI = 161.0, 323.0


def main():
    print('=' * 74)
    print('① 同一个量、五份来源 —— 六倍离散')
    print('=' * 74)
    print('  问题：一个过孔的热阻是多少？（Ø0.3 钻 / 25µm 镀 / 1.6mm 板）')
    print()
    print('  %s %s %s' % (pad('来源', 18), pad('值 K/W', 12), '级别'))
    for name, v, lv in sorted(SOURCES, key=lambda x: x[1]):
        print('  %s %s %s' % (pad(name, 18), pad('%g' % v, 12), lv))
    print()
    lo = min(v for _n, v, _l in SOURCES)
    hi = max(v for _n, v, _l in SOURCES)
    print('  范围 **%.0f ~ %.0f**，相差 **%.1f 倍**。' % (lo, hi, hi / lo))
    print()
    print('  ★★ 注意"级别"那一列：**最可信的那一级是空的**。')
    print('     A 级（亲自读过的一手原文）**一条都没有** ——')
    print('     厂商文档域全部不可达，五份里没有一份是原文。')
    print()
    print('  ★★★ 所以文档写了一句硬话：')
    print('       **"不许从中挑一个顺手的用。"**')
    print()
    print('  ⚠️ 为什么"挑顺手的"特别危险：因为**离散的方向性**。')
    print('     这不是随机的 ±5%%，是 **%.1f 倍**的跨度。' % (hi / lo))
    print('     想论证"散热够"，就挑 70；想论证"需要大散热片"，就挑 407。')
    print('     **两边都能挑到支持自己的数** —— 这正是"为已选答案找理由"。')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('② 一条"看起来有依据"的结论，错在哪')
    print('=' * 74)
    print('  文档里曾写过一句话：铜填比开口孔**好 4~8 倍**。')
    print('  它引的是标准里的"类型号"，看起来很有依据。')
    print()
    print('  复核时发现：那个"类型号"描述的是**构造**（填满并盖帽），')
    print('  **不是填充材料**。而厂家实际给的材料是"铜浆"：')
    print()
    print('    纯铜导热系数        **%.0f** W/(m·K)' % K_COPPER)
    print('    厂家的"铜浆"        **%.0f** W/(m·K)' % K_PASTE)
    print('    ⇒ 差 **%.1f 倍**。' % (K_COPPER / K_PASTE))
    print()
    print('  ★★ 名字里有个"铜"字，导热系数差 %.0f 倍 ——' % (K_COPPER / K_PASTE))
    print('     **这就是那句话错掉的全部原因。**')
    print()
    print('  按厂家实际参数重算（孔壁铜 ∥ 孔芯填充）：')
    print()
    print('  %s %s %s' % (pad('情形', 22), pad('单孔 K/W', 12), '说明'))
    print('  %s %s %s'
          % (pad('Ø0.40 裸孔', 22), pad('%.1f' % R_BARE_04, 12), '孔壁铜一条路'))
    print('  %s %s %s'
          % (pad('Ø0.40 + 铜浆', 22), pad('%.1f' % R_FILL_04, 12),
             '并联上孔芯，但孔芯几乎不导热'))
    imp = (R_BARE_04 - R_FILL_04) / R_BARE_04
    print()
    print('  ⇒ 改善只有 **%.1f%%**（不是 4~8 倍）。' % (imp * 100))
    print()
    print('  ★★★ 结论：**主导路径始终是那 25µm 的孔壁铜。**')
    print('       塞什么进去几乎不影响导热 —— 因为塞进去的东西导热很差。')
    print()
    print('  ★ 那塞孔还有价值吗？**有，但在别的地方** ——')
    print('    它的价值不是"每个孔更导热"，而是"**孔可以打进焊盘里**"。')
    print('    那是**几何收益**，不是热收益。（下一节就是"为什么几何才是要害"。）')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('③ 几何把这条路判死 —— 而且它不依赖任何有争议的常数')
    print('=' * 74)
    print('  规范要求：每颗功率管的散热盘下 **≥ %d 个**过孔。' % REQUIRED_HOLES)
    print()
    print('  板上实测的散热盘：%.3f × %.3f mm = **%.2f mm²**'
          % (PAD_W, PAD_H, PAD_W * PAD_H))
    print()
    print('  厂家口径：孔径 %.1f、盘径 %.1f、孔到盘边 ≥ %.1f mm' % (VIA_D, VIA_PAD, EDGE_MIN))
    print()
    # 孔心到盘边的距离 = 边距 + 孔半径
    need = EDGE_MIN + VIA_D / 2.0
    usable_w = PAD_W - 2 * need
    usable_h = PAD_H - 2 * need
    print('  ⇒ 孔心距盘边至少 %.1f mm ⇒ 盘内可用的"孔心区"：' % need)
    print('      宽 %.3f − 2×%.1f = **%.3f mm**' % (PAD_W, need, usable_w))
    print('      长 %.3f − 2×%.1f = **%.3f mm**' % (PAD_H, need, usable_h))
    print()
    if usable_w < VIA_PAD or usable_h < VIA_PAD:
        n_w, n_h = 0, 0
    else:
        n_w = int(usable_w // VIA_PAD) + 1
        n_h = int(usable_h // VIA_PAD) + 1
    print('  排法 A（文档口径，盘间还要留余量）：**%d 孔**' % DOC_HOLES)
    print('  排法 B（本脚本口径，孔间距 = 盘径 %.1f mm）：**%d × %d = %d 孔**'
          % (VIA_PAD, n_w, n_h, n_w * n_h))
    print()
    print('  ★★ 两种排法差 %.0f 倍 —— 但**要求是 %d 孔**：'
          % (float(n_w * n_h) / DOC_HOLES, REQUIRED_HOLES))
    print('     排法 A 差 **%.0f 倍**，排法 B 也差 **%.0f 倍**。'
          % (REQUIRED_HOLES / float(DOC_HOLES),
             REQUIRED_HOLES / float(n_w * n_h)))
    print()
    print('  ★★★ 所以"排法怎么定"这个分歧**不影响结论** ——')
    print('       差一倍也好、差四倍也好，**都远远不够**。')
    print('       **这不是"难做"，是"物理不可能"。**')
    print()
    print('  （这与第 8 章"结论对模型不敏感"是同一个手法：')
    print('    当结论在最松和最紧两种算法下都成立时，不必先争算法。）')
    print()
    print('  ★★★ 而这一条为什么比 ① 那五份来源都可信？')
    print('       因为它**只用了三个量**：盘尺寸（板上量的）、')
    print('       孔径与边距（厂家答复的）、板厚。')
    print('       它**不涉及**镀层厚度、FR4 的导热系数、扩散模型 ——')
    print('       而 ① 那五份来源的分歧**全在这些量上**。')
    print()
    print('  ⇒ **判据：按"这个结论依赖什么"给证据排序，而不是按来源的牌子。**')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('④ 出口：把散热口从"盘"挪到"本网铜岛"')
    print('=' * 74)
    print('  盘上塞不下孔，但**盘外可以**。')
    print('  如果该网在本层铺成一块铜岛，孔就不受那个小盘子的限制了：')
    print()
    print('  %s %s %s' % (pad('孔打在哪', 18), pad('孔数', 10), '并联热阻 K/W'))
    print('  %s %s %s'
          % (pad('盘内（几何上限）', 18), pad('%d' % DOC_HOLES, 10),
             '%.1f  ← **白打**' % R_IN_PAD))
    print('  %s %s %s'
          % (pad('本网铜岛内', 18), pad('%d' % ISLAND_HOLES, 10),
             '%.1f  ← **够用**' % R_IN_ISLAND))
    print()
    print('  ★★ 孔数从 %d 涨到 %d（%.0f 倍），热阻从 %.1f 掉到 %.1f（%.0f 倍）。'
          % (DOC_HOLES, ISLAND_HOLES, float(ISLAND_HOLES) / DOC_HOLES,
             R_IN_PAD, R_IN_ISLAND, R_IN_PAD / R_IN_ISLAND))
    print('     而**做到它的代价**只是：本层多铺一块铜，孔挪到铜上去。')
    print()
    print('  ★★★ 所以设计要求应该改写成**几何要求**：')
    print('       「每颗功率管的**漏极网**在本层要有一块**足够大的铜岛**，')
    print('         岛上打足够多的孔接到同网的内层铜。」')
    print('       —— 而不是「每盘 ≥%d 孔」（那个做不到）。' % REQUIRED_HOLES)
    print()
    print('  ★ 注意这条改写的形状：**把一条做不到的要求，')
    print('    换成一条等价意图、但做得到的要求。**')
    print('    （与第 8 章"从距离改成可标定性"是同一手法。）')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('⑤ 模型唯一的独立校验')
    print('=' * 74)
    print('  上面那个"铜岛要多大"不是拍脑袋 —— 它是模型算出来的饱和尺度。')
    print('  而模型需要一次**独立校验**：')
    print()
    print('  %s %s' % (pad('来源', 22), '饱和面积 mm²'))
    print('  %s %s' % (pad('厂商手册实测', 22),
                       '%.0f ~ %.0f' % (AN821_LO, AN821_HI)))
    print('  %s %s' % (pad('本机模型（标称口径）', 22), '161  ← 落在区间**下沿**'))
    print()
    print('  ★★ 这是本模型**唯一的独立校验，而它过了**。')
    print('     18 组参数里 9 组落在厂商实测区间内，其余在两侧边界外**单调排列**。')
    print()
    print('  ★★★ 一句话：**模型可以自洽、可以跑通、可以给出漂亮的数，')
    print('       但"能复现一个别人量出来的数"才是它唯一的立足点。**')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('自检 —— 排序与比值必须自洽')
    print('=' * 74)
    # ① 离散必须真的很大（否则"不许挑"这句话没理由）
    assert hi / lo > 3.0, '① 离散不够大，"不许挑一个顺手的"理由不成立'
    print('  ✓ 五份来源跨度 %.1f 倍（%.0f ~ %.0f）' % (hi / lo, lo, hi))
    # ② 铜浆必须比铜差一个数量级，否则"4~8 倍"那句话本来就对
    assert K_COPPER / K_PASTE > 10, '② 铜浆与铜的差距不够大'
    assert 0 < imp < 0.2, '② 塞孔的改善幅度不在一成上下'
    print('  ✓ 铜浆比铜差 %.1f 倍 ⇒ 塞孔只改善 %.1f%%' % (K_COPPER / K_PASTE, imp * 100))
    # ③ 几何上限必须真的低于要求（否则"物理不可能"这条结论不成立）
    assert n_w * n_h < REQUIRED_HOLES, '③ 几何上限居然够 —— 结论反了'
    print('  ✓ 几何上限 %d 孔 < 要求 %d 孔（差 %.0f 倍）'
          % (n_w * n_h, REQUIRED_HOLES, REQUIRED_HOLES / float(n_w * n_h)))
    # ④ 挪到岛上必须真的更优（否则"出口"不成立）
    assert R_IN_ISLAND < R_IN_PAD, '④ 岛内没比盘内好 —— 出口不成立'
    print('  ✓ 盘内 %.1f → 岛内 %.1f K/W（好 %.0f 倍）'
          % (R_IN_PAD, R_IN_ISLAND, R_IN_PAD / R_IN_ISLAND))
    # ⑤ 厂商区间必须是个区间且为正
    assert 0 < AN821_LO < AN821_HI, '⑤ 厂商区间不成立'
    print('  ✓ 厂商实测区间 %.0f ~ %.0f mm²，模型值 161 落在下沿'
          % (AN821_LO, AN821_HI))
    print()
    print('  ✅ 自检通过')
    print()
    print('=' * 74)
    print('口径：五份来源的数值、厂家参数、盘尺寸、孔数与饱和点均取自二代设计文档')
    print('      21/28 的实测与厂商答复记录。')
    print('      ⚠️ 本脚本**没有一手标准原文**（原文未获取）——')
    print('         所以它复算的是"文档怎么排证据"，不是"标准说什么"。')
    print('=' * 74)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
