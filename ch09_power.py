# -*- coding: utf-8 -*-
"""ch09_power.py —— 卷 9 第 5 章：电源先有判据，才有方案

## 这一章要讲的事

二代的电源架构**改了四轮**。每一轮都不是"换个想法试试"，
而是**一条判据把上一个方案否掉了**：

    | 轮次 | 方案 | 被哪条判据否掉 |
    |---|---|---|
    | 一   | 加一级升压母线   | 升压级本身要面对全输入范围 |
    | 二   | 隔离式多输出     | 输入是电池，**本来就没有隔离要求** |
    | 三   | buck ‖ boost 前级 | 器件**拿绝对最大当工作电压** |
    | 四   | 直通 + 拆板      | —— 定案 |

**本章讲的是这三条判据，不是那个结论。**

## 三条判据，都能算

① **占空比范围** —— 一个把方案直接否掉的数（5.6 : 1 vs 18 : 1）
② **量级比**     —— 什么时候"一块板"这件事本身不成立（56 倍）
③ **载流宽度**   —— IPC-2221 公式 + 一次标定（内层要 2.6 倍宽）

## 本脚本做三件事

① 复算占空比范围，看它怎么把方案否掉
② 复算两个电流量级，看"拆板"这条线画在哪
③ 复算载流宽度，**先标定公式**再算，并复现文档里的整张表

跑法：python code/ch09_power.py
"""

import unicodedata


def pad(s, n):
    """按**显示宽度**补齐 —— `%-Ns` 数的是字符数，汉字占两列，会排歪。"""
    return s + ' ' * max(0, n - sum(
        2 if unicodedata.east_asian_width(c) in 'WF' else 1 for c in s))


# ---- ① 占空比范围（文档 14 §11.1 的对比表）----
#     (方案, D_min, D_max, 说明)
DUTY = [
    ('隔离式半桥', 0.08, 0.45, '变压器匝比把范围压住了'),
    ('四路直入',   0.05, 0.90, '每一路都要独自面对全输入范围'),
]

# ---- ② 两个量级（文档 18 §4）----
DIRECT_PEAK = 420.0     # 直通段峰值电流 A（电池总线，走铜排/端子）
FRONT_END = 7.5         # 前级取电 A（板子自己吃的那部分）
PCB_LIMIT = 30.0        # 文档给的经验线：超过它就不该走 PCB

# ---- ③ IPC-2221 载流公式（文档 14 §2、18 §9）----
#     I = k · ΔT^0.44 · A^0.725      A 单位 mil²
K_OUTER = 0.048         # 外层：两面散热
K_INNER = 0.024         # 内层：只有一面散热 —— 恰好一半
DT = 10.0               # 允许温升 °C
MIL2_PER_MM2 = 1550.0

# 标定点（文档 18 §9.2 的"尺子自证"）：旧表 P1「16.6 A ⇒ 7.3 mm」
CAL_I, CAL_W_MM, CAL_COPPER_MM = 16.6, 7.3, 0.070   # 外层 2 oz

# 逐档宽度（12.54 A 母线，即 388.7 W ÷ 31 V）
BUS_I = 12.54
STACKS = [
    ('外层 F+B 并联 1 oz', K_OUTER, 0.035 * 2, 4.92),
    ('内层两层      2 oz', K_INNER, 0.070 * 2, 6.39),
    ('内层两层      1 oz', K_INNER, 0.035 * 2, 12.79),
    ('内层单层      2 oz', K_INNER, 0.070,     12.79),
    ('内层单层      1 oz', K_INNER, 0.035,     25.57),
    ('内层单层    0.5 oz', K_INNER, 0.0175,    None),
]


def width_mm(cur, k, copper_mm):
    """IPC-2221 反解所需**线宽**（mm）。

        A_mil2 = (I / (k · ΔT^0.44))^(1/0.725)
        宽 = (A_mil2 / 1550) / 铜厚
    """
    a_mil2 = (cur / (k * DT ** 0.44)) ** (1.0 / 0.725)
    return (a_mil2 / MIL2_PER_MM2) / copper_mm


def main():
    print('=' * 74)
    print('① 判据一：占空比范围 —— 一个能把方案否掉的数')
    print('=' * 74)
    print('  同一个输入范围（0–100 V）要做出同样的几路输出，')
    print('  不同拓扑的**占空比跨度**差得很远：')
    print()
    print('  %s %s %s %s %s' % (pad('方案', 14), pad('D_min', 10), pad('D_max', 10),
                                pad('范围比', 12), '说明'))
    for name, dmin, dmax, why in DUTY:
        print('  %s %s %s %s %s'
              % (pad(name, 14), pad('%.0f%%' % (dmin * 100), 10),
                 pad('%.0f%%' % (dmax * 100), 10),
                 pad('%.1f : 1' % (dmax / dmin), 12), why))
    print()
    r_iso = DUTY[0][2] / DUTY[0][1]
    r_dir = DUTY[1][2] / DUTY[1][1]
    print('  ★ 范围比 = D_max ÷ D_min，它就是"这一级难不难做"的**第一因素**：')
    print('    · %.1f : 1 —— 变压器匝比先把范围压住，控制器只在小跨度里调'
          % r_iso)
    print('    · %.0f : 1 —— **两端都难**：占空比小要撞最小导通时间与抖动，' % r_dir)
    print('                    占空比大要撞退饱和')
    print()
    print('  ★★ 更狠的一层：四路直入要**做四遍** ——')
    print('     等于把最难做的那件事**复制了 4 份**。')
    print('     ⇒ 判据不是"哪条路单路最难"，是"**难的那部分要做几次**"。')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('② 判据二：量级 —— 什么时候"一块板"这件事本身不成立')
    print('=' * 74)
    print('  板上其实有**两股完全不同的电流**：')
    print()
    print('    直通段（电池总线穿板而过，只做测量）：%.0f A 峰值' % DIRECT_PEAK)
    print('    前级取电（板子自己吃的那部分）：        %.1f A' % FRONT_END)
    print()
    print('    ⇒ 相差 **%.0f 倍**。' % (DIRECT_PEAK / FRONT_END))
    print()
    print('  ★★ 而这两股电流对 PCB 的要求是**相反的**：')
    print('     大电流要"越宽越好、最好别在板上"；')
    print('     前级要"多几层、多几种铜厚、精细控制"。')
    print()
    print('     经验线：**超过 %.0f A 就不该走 PCB**。' % PCB_LIMIT)
    print('     ⇒ 一个 %.0f A 的直通段和一个 %.1f A 的前级，' % (DIRECT_PEAK, FRONT_END))
    print('       **没有任何一种工艺能同时满足**。这就是拆板最硬的一条理由。')
    print()
    print('  ⚠️ 但有一条**反直觉**的，必须说清：')
    print('     "电压高所以电流大"**只对直通段成立**。')
    print('     板子自己的取电**恰好相反 —— 输入越低越吃力**：')
    print('     输入从 100 V 掉到 30 V，同样的功率下电流涨 3 倍多。')
    print('     ⇒ **按最低输入电压设计前级**，不是按标称电压。')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('③ 判据三：载流宽度 —— 先标定公式，再算')
    print('=' * 74)
    print('  IPC-2221 的载流式（A 单位 mil²）：')
    print()
    print('    I = k · ΔT^0.44 · A^0.725      （A 单位 mil²）')
    print('    k  = %.3f（外层，两面散热） / %.3f（内层，只有一面）'
          % (K_OUTER, K_INNER))
    print('    ΔT = %.0f °C（允许温升，全板统一取一档）' % DT)
    print()
    print('  ★ 动手算之前**先标定**（文档 18 §9.2 的规矩：先证尺子，再量板子）：')
    cal = width_mm(CAL_I, K_OUTER, CAL_COPPER_MM)
    print('    旧表有一行「%.1f A ⇒ %.1f mm」（外层 2 oz）。' % (CAL_I, CAL_W_MM))
    print('    本式算得 **%.2f mm** —— 与旧表同源，可以直接用。' % cal)
    print()
    print('  那么 %.2f A 的母线需要多宽：' % BUS_I)
    print()
    print('  %s %s %s %s' % (pad('叠层', 22), pad('k', 8),
                            pad('铜厚', 10), '所需线宽'))
    for label, k, cu, _ref in STACKS:
        w = width_mm(BUS_I, k, cu)
        print('  %s %s %s %s'
              % (pad(label, 22), pad('%.3f' % k, 8),
                 pad('%.4f mm' % cu, 10),
                 pad('%.2f mm' % w, 12)
                 + ('（实际不可行）' if w > 20 else '')))
    print()
    print('  ★★ 最要紧的是 **k 那一列**：外层 %.3f、内层 %.3f —— 恰好一半。'
          % (K_OUTER, K_INNER))
    ratio = (K_OUTER / K_INNER) ** (1.0 / 0.725)
    print('     但这一半**不是**让宽度翻倍，而是 **%.1f 倍**：' % ratio)
    print('     因为宽度是 k 的 -(1/0.725) 次方 —— **指数在放大它**。')
    print()
    print('  ★ 所以"内层也能走大电流"这句话**要看铜厚**：')
    print('    内层用两层 2 oz 并联（%.2f mm）才勉强进 7 mm；'
          % width_mm(BUS_I, K_INNER, 0.140))
    print('    内层单层 0.5 oz 要 **%.1f mm** —— 比板子还宽，直接排除。'
          % width_mm(BUS_I, K_INNER, 0.0175))

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('④ 一条通用判据：绝对最大不是工作电压')
    print('=' * 74)
    print('  同一份设计资料里，某个方案的器件是按"手册上写着 100 V"选的。')
    print('  复核时把整族器件翻了一遍，发现同一件事：')
    print()
    print('    宣称 **100 V** 的那些型号，**推荐工作上限一律 %d V 或更低**。' % 80)
    print('    ⇒ 稳态就顶到绝对最大的选型，**在这条路上一个都不成立**。')
    print()
    print('  ★★ 差 %d V，看着不大，但这两栏管的是**完全不同的两件事**：' % (100 - 80))
    print('     · 绝对最大 = "再往上器件会坏"（一次性的边界）')
    print('     · 推荐工作 = "一直待在这儿也没事"（持续的边界）')
    print()
    print('  ⚠️ 而且这一族的器件在**整个家族里**都这么标 ——')
    print('     不是某一颗的特例。⇒ 判据要按**族**查，不能只查选中的那颗。')

    print()
    print('=' * 74)
    print('⑤ 四条判据合起来，把架构一路逼到唯一解')
    print('=' * 74)
    print('  %s %s' % (pad('判据', 20), '它否掉了什么'))
    rows = [
        ('占空比范围', '让最难的跨度只做一次（隔离），而不是做四遍'),
        ('隔离的必要性', '输入是电池、本来就无隔离要求 ⇒ 隔离白付代价'),
        ('绝对最大 ≠ 工作', '把"耐压"当"工作电压"选的器件，全部出局'),
        ('量级比', '直通段与前级差 %.0f 倍 ⇒ 一块板放不下' % (DIRECT_PEAK / FRONT_END)),
        ('载流宽度', '内层要 2.6 倍宽 ⇒ 铜厚与层数必须一起定'),
    ]
    for a, b in rows:
        print('  %s %s' % (pad(a, 20), b))
    print()
    print('  ★★★ 注意这张表里**没有一行是"哪个方案更好"**。')
    print('     全是"**哪条路在给定条件下成立**" ——')
    print('     判据的作用不是排序，是**排除**。')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('自检 —— 公式与换算必须复现文档里的整张表')
    print('=' * 74)
    ok = 0
    for label, k, cu, ref in STACKS:
        if ref is None:
            continue
        got = width_mm(BUS_I, k, cu)
        d = abs(got - ref) / ref
        assert d < 0.01, '③ %s：算得 %.2f，文档记 %.2f（差 %.1f%%）' % (
            label, got, ref, d * 100)
        ok += 1
    print('  ✓ %.2f A 的五档宽度全部复现（误差 <1%%），与文档 6.39/12.79/4.92… 一致'
          % BUS_I)
    print('     （共核 %d 档）' % ok)
    # 标定点
    assert abs(cal - CAL_W_MM) / CAL_W_MM < 0.01, '③ 标定点对不上'
    print('  ✓ 标定点 %.1f A ⇒ %.2f mm（旧表 %.1f mm）' % (CAL_I, cal, CAL_W_MM))
    # k 的比值必须是 2（内层只有一面散热）
    assert abs(K_OUTER / K_INNER - 2.0) < 1e-9, '③ 内外层 k 不是 2 倍关系'
    print('  ✓ 内层 k = 外层 k 的一半（%.3f / %.3f），宽度放大 **%.1f 倍**'
          % (K_OUTER, K_INNER, ratio))
    # 占空比：隔离方案必须真的比直入方案窄
    assert r_iso < r_dir, '① 范围比方向反了'
    print('  ✓ 占空比范围 %.1f : 1 < %.0f : 1（隔离确实把范围压窄了）'
          % (r_iso, r_dir))
    # 量级比必须真的超过经验线，否则"拆板"这条结论不成立
    assert DIRECT_PEAK / FRONT_END > 10, '② 量级差不够大，拆板理由不成立'
    assert DIRECT_PEAK > PCB_LIMIT > FRONT_END, '② 经验线没落在两个量级之间'
    print('  ✓ 量级比 %.0f 倍，经验线 %.0f A 正好落在两者之间'
          % (DIRECT_PEAK / FRONT_END, PCB_LIMIT))
    print()
    print('  ✅ 自检通过')
    print()
    print('=' * 74)
    print('口径：占空比端点、电流量级、铜厚与旧表宽度取自二代设计文档 14/17/18；')
    print('      载流公式用文档给的 IPC-2221 形式，并**先在旧表上标定**。')
    print('      本脚本是代数复算，**没有实测** —— 本机没有这块板。')
    print('=' * 74)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
