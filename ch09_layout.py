# -*- coding: utf-8 -*-
"""ch09_layout.py —— 卷 9 第 6 章：几何是硬的

## 这一章要讲的事

布局布线里，"放不下"常常被当成一个**感觉**：
"这里有点挤"、"再调调应该能过"。

**它不是感觉，是几何。** 本章把四件事算出来：

① **放得下吗** —— 用**布线密度**比，不靠目测（0.369 vs 0.501 段/mm²）
② **少铺点铜是不是就能走通** —— 是零和，实测方向单调
③ **把线改细能不能救** —— 缝就那么宽，算出来就知道不能
④ **问题在哪** —— 用**分布**定位，不是用**计数**

## 一句可以带走的话

③ 那一节算出来的是：**0.20 的线穿 0.20 的缝，每边只剩 0.0365mm。**
而这个 **0.0365 与"线够不够细"无关** —— 它就是缝减去线宽再对半分。

⇒ **当一道约束在数学上不成立时，改参数是没用的，得改做法。**

跑法：python code/ch09_layout.py
"""

import unicodedata


def pad(s, n):
    """按显示宽度补齐（汉字占两列）。"""
    return s + ' ' * max(0, n - sum(
        2 if unicodedata.east_asian_width(c) in 'WF' else 1 for c in s))


# ---- ① 布线密度（文档 18 §9.4）----
#     (设计, 可用信号层数, 走线段数, 板面积 mm²)
DENSITY = [
    ('参考设计',   2, 5313, 14400),
    ('本板（改后）', 2, 5863, 11700),
]

# ---- ② 零和实测（文档 22 §0）----
#     铺铜块数与 FR 布线结果是**单调反向**的
ZERO_SUM = [
    ('铺铜少时', 72, 4657, 137),
    ('铺铜多时', 264, 4084, 198),
]

# ---- ③ 缝的数学（文档 12 §4 / §5）----
PAD_W = 0.300      # 连接器焊盘宽 mm
PAD_PITCH = 0.500  # 同行相邻焊盘中心距 mm
MIN_TRACE = 0.127  # 板的最小线宽 mm
RULE_CLR = 0.150   # 本板默认间距规则 mm


def main():
    print('=' * 74)
    print('① "放得下吗" —— 用布线密度比，不靠目测')
    print('=' * 74)
    print('  换层之前必须先回答：换成更少的信号层，还走得通吗？')
    print('  这个问题可以**比**出来 —— 拿一个公认不挤的设计当尺子：')
    print()
    print('  %s %s %s %s %s'
          % (pad('设计', 14), pad('信号层', 10), pad('走线段数', 12),
             pad('板面积', 12), '密度'))
    for name, layers, seg, area in DENSITY:
        print('  %s %s %s %s %s'
              % (pad(name, 14), pad('%d 层' % layers, 10),
                 pad('%d 段' % seg, 12), pad('%d mm²' % area, 12),
                 '%.3f 段/mm²' % (seg / float(area))))
    d0 = DENSITY[0][2] / float(DENSITY[0][3])
    d1 = DENSITY[1][2] / float(DENSITY[1][3])
    print()
    print('  ★ 本板比参考设计密 **%.0f%%** —— **同一个量级**。' % ((d1 / d0 - 1) * 100))
    print('    ⇒ 这就是"放得下"的判据：**不是一个感觉，是一个比值**。')
    print()
    print('  ⚠️ 注意它证明的是"**同一量级**"，不是"一定成功"。')
    print('     它排除的是"差一个数量级、根本没戏"这一类，')
    print('     剩下的还得靠布线器真跑一遍（② 就是那一遍）。')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('② "少铺点铜是不是就通了" —— 零和，实测方向单调')
    print('=' * 74)
    print('  背景：板子原本是 **%d 层**，功率铺铜与信号走线挤在一起；' % 4)
    print('  后来要改成 **%d 层**把两者分开（下面就是"为什么必须改"的实测）。' % 6)
    print()
    print('  功率铺铜和信号走线**抢同一批层**。一个很自然的想法是：')
    print('  "少铺一点给走线让路"。实测结果：')
    print()
    print('  %s %s %s %s'
          % (pad('情形', 12), pad('铺铜块数', 12), pad('走线', 10), '未连接'))
    for name, zones, seg, unconn in ZERO_SUM:
        print('  %s %s %s %s'
              % (pad(name, 12), pad('%d 块' % zones, 12),
                 pad('%d 段' % seg, 10), '%d 条' % unconn))
    print()
    dz = ZERO_SUM[1][1] - ZERO_SUM[0][1]
    ds = ZERO_SUM[1][2] - ZERO_SUM[0][2]
    du = ZERO_SUM[1][3] - ZERO_SUM[0][3]
    print('  铺铜 +%d 块 ⇒ 走线 %+d 段、未连接 %+d 条。' % (dz, ds, du))
    print()
    print('  ★★ **方向是单调的**：铺铜每多一点，走线能力就少一点。')
    print('     而且这不是"效率略降"，是**未连接数一路上涨**。')
    print()
    print('  ⚠️ 还有一个更隐蔽的根因，值得单独记：')
    print('     布线器**不穿过任何铺铜** —— **包括它自己那一网的铺铜**。')
    print('     ⇒ 铺铜吃掉的不是"异网的走线空间"，是**所有网的走线空间**。')
    print()
    print('  ★★★ 所以"少铺一点"是**零和**：省下来的走线能力，')
    print('       正好等于多出来的走线需求。**走不通。**')
    print('       ⇒ 唯一的出路是把两个需求**解耦到不同的层**上，')
    print('         而不是在同一层里找平衡。')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('③ "把线改细能不能救" —— 算一下缝，就知道不能')
    print('=' * 74)
    print('  场景：一个高密度连接器，引脚很密，每条信号线旁边还夹着地线。')
    print()
    print('  焊盘宽 %.2f mm，同行相邻焊盘中心距 %.2f mm' % (PAD_W, PAD_PITCH))
    gap = PAD_PITCH - PAD_W
    print('  ⇒ 相邻焊盘之间的**净缝只有 %.2f mm**' % gap)
    print()
    print('  原来是怎么走的：**斜着**从焊盘穿过净缝，接到横向的总线上。')
    print('  斜穿时，线在缝里是斜的，不可避免地**蹭到相邻焊盘的角**。')
    print()
    print('  那把线压细呢？压到板的最小线宽 %.3f mm，每边还剩：' % MIN_TRACE)
    side = (gap - MIN_TRACE) / 2.0
    print('    (%.2f − %.3f) ÷ 2 = **%.4f mm**' % (gap, MIN_TRACE, side))
    print('    而规则要求 %.2f mm ⇒ 差 **%.1f 倍**。' % (RULE_CLR, RULE_CLR / side))
    print()
    print('  ★★ 关键在这：**%.4f 这个数里没有"线够不够细"的自由度。**' % side)
    print('     它就是"缝减线宽再对半分"。线再细，也只能让这个数慢慢涨，')
    print('     而缝本身是**焊盘尺寸和脚距定的** —— 那条路封死了。')
    print()
    print('  换走法呢？**垂直出脚**（沿着焊盘自己那一列走出去，不穿缝）：')
    vert = PAD_PITCH - RULE_CLR - MIN_TRACE / 2.0
    print('    %.2f − %.2f − %.3f ÷ 2 = **%.4f mm**' % (
        PAD_PITCH, RULE_CLR, MIN_TRACE, vert))
    print('    ⇒ 连板子自己的 %.2f mm 规则都**富余**。' % RULE_CLR)
    print()
    print('  ⚠️ 但要说句公道话：**原来的斜线不是蠢。**')
    print('     斜着走是为了**在障碍之间穿过去** —— 那个需求是真的。')
    print('     它只是**穿得太贴了**。')
    print()
    print('  ★★★ 所以结论不是"改细"，是**改做法**：')
    print('       **当一道约束在数学上不成立时，调参数是没用的。**')
    print()
    print('  ⚠️ 那"放宽规则"呢？（有人会想：把 0.15 放宽到 0.10 不就过了？）')
    relaxed = 0.100
    print('     %.4f mm 对放宽后的 %.2f mm —— **仍然不够**，还差 %.1f 倍。'
          % (side, relaxed, relaxed / side))
    print('     而且放宽是**全板**的：为了这一处放过别处真正危险的地方，')
    print('     代价远大于收益。⇒ **改规则也救不了一条不成立的几何。**')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('④ 用"分布"定位问题，而不是用"计数"')
    print('=' * 74)
    print('  自检报出 17 处间距不足。**17 这个数本身没告诉你任何事** ——')
    print('  是"全板工艺不行"，还是"某一个角落挤"？')
    print('  把全板的两两间距**分档**数一遍，答案就出来了：')
    print()
    print('  %s %s %s' % (pad('间距区间', 18), pad('对数', 10), '备注'))
    dist = [
        ('< 0.10 mm', 14, '**全部是违规**'),
        ('0.10 – 0.15 mm', 3, '**全部是违规**'),
        ('0.15 – 0.20 mm', 827, '合规，而且是最密的一档'),
        ('0.20 – 0.30 mm', 563, '合规'),
    ]
    for rng, n, note in dist:
        print('  %s %s %s' % (pad(rng, 18), pad('%d 对' % n, 10), note))
    print()
    bad = dist[0][1] + dist[1][1]
    print('  ★ 低于规则的 %d 对 = %d + %d —— **全部落在同一个连接器的扇出区**。'
          % (bad, dist[0][1], dist[1][1]))
    print('    而其余**最密的 %d 对都在 0.15–0.20 档**，全都合规。' % dist[2][1])
    print()
    print('  ★★ 分布一旦摆出来，问题的**性质**就变了：')
    print('     · 不是"全板工艺能力不够" ⇒ 换板厂、放宽全板规则都**没用**；')
    print('     · 是"**一颗连接器的扇出**密度问题" ⇒ 只需要改那一处。')
    print()
    print('  ★★★ 判据：**光有计数只能知道"有多少"；')
    print('       把它分档，才知道"在哪、是什么性质"。**')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('自检 —— 算式与换算必须自洽')
    print('=' * 74)
    # ① 密度比必须真的在同一量级（比值 < 2），否则"放得下"这条结论不成立
    assert 1.0 < d1 / d0 < 2.0, '① 密度比不在"同一量级"内'
    print('  ✓ 密度 %.3f vs %.3f 段/mm²，比值 %.2f（同一量级）' % (d0, d1, d1 / d0))
    # ② 零和必须是单调的：铺铜↑ ⇒ 走线↓ 且 未连接↑
    assert ds < 0 and du > 0, '② 零和方向反了'
    print('  ✓ 铺铜 +%d 块 ⇒ 走线 %+d、未连接 %+d（单调反向）' % (dz, ds, du))
    # ③ 斜穿的余量必须真的不够，垂直出脚必须真的够 —— 否则"改做法"的结论不成立
    assert side < RULE_CLR, '③ 斜穿居然够 —— 改做法的理由不成立'
    assert vert > RULE_CLR, '③ 垂直出脚也不够 —— 结论反了'
    print('  ✓ 斜穿每边 %.4f mm（< %.2f 不够）；垂直出脚 %.4f mm（> %.2f 够）'
          % (side, RULE_CLR, vert, RULE_CLR))
    # ④ 违规必须全部落在最低两档，且第三档必须远大于违规数（否则分布没有区分度）
    assert bad == 17, '④ 违规数与文档不符'
    assert dist[2][1] > bad * 10, '④ 分布没有区分度'
    print('  ✓ 违规 %d 对全在最低两档；下一档 %d 对（区分度 %.0f 倍）'
          % (bad, dist[2][1], dist[2][1] / float(bad)))
    print()
    print('  ✅ 自检通过')
    print()
    print('=' * 74)
    print('口径：密度、铺铜/走线计数、间距分布、焊盘与脚距取自二代设计文档 12/18/22；')
    print('      本脚本只做代数复算与分档统计，**没有实测** —— 本机没有这块板。')
    print('=' * 74)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
