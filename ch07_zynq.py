# -*- coding: utf-8 -*-
"""ch07_zynq.py —— 卷 7 第 11 章：把 Zynq 方案里的几个数算清楚

第 11 章讲的是 Zynq-7020 做飞控的架构决策。那份设计文档里
有一处"PL 加速四元数积分"的估算，本脚本把它**重算一遍**。

要算的东西：

  ① 四元数姿态积分一步到底要多少次运算（这个可以精确数）
  ② 在 Cortex-A9 上大概要多久（**文档给的估计**，不是本脚本测的）
  ③ 放进 PL 做成流水线，一拍要多久 —— 这一步只是 `1 / 时钟频率`
  ④ ★ 于是能发现文档里的一处**自相矛盾**：
     "50 MHz 时钟、一拍完成"对应的是一拍 20 ns，而文档写的是 10 ns。
     两个数差 2 倍，加速比也就跟着差 2 倍。

★ 这个脚本的意义不在于"算得准"（②是估计），而在于**加减乘除要自洽**：
  同一段话里的几个数如果互相推不出来，那多半有一个是错的 ——
  而这正是本丛书反复在做的事：**任何引用来的数字，都要能被重算。**

跑法：python code/ch07_zynq.py
"""

import math


def main():
    print('=' * 72)
    print('① 四元数姿态积分一步的运算量（可精确计数）')
    print('=' * 72)
    # 姿态更新：q ← q ⊗ Δq，Δq 由角增量构造
    ops = [
        ('构造 Δq（由角速度 × 周期）', 4, 3, 0),      # 四元数微分 → 增量
        ('q ⊗ Δq（四元数乘法）',       16, 12, 0),
        ('归一化（含 1 次 sqrt）',      8, 3, 1),
    ]
    mul = add = sq = 0
    print('  %-28s %6s %6s %6s' % ('步骤', '乘法', '加法', '开方'))
    for name, m, a, s in ops:
        mul += m; add += a; sq += s
        print('  %-28s %6d %6d %6d' % (name, m, a, s))
    print('  %-28s %6d %6d %6d' % ('合计', mul, add, sq))
    print()
    print('  ★ 这些是**数出来的**，不是估的：四元数乘法就是 16 乘 12 加。')
    print('    （浮点除法通常另算，这里并进"加法"那一列的余量里。）')

    # -----------------------------------------------------------------------
    print()
    print('=' * 72)
    print('② 在 Cortex-A9 上大概多久（**设计文档给的估计**，本脚本不测）')
    print('=' * 72)
    A9_MHZ = 667.0
    A9_NS = 200.0                       # 文档给的估计值
    print('  文档给的估计：%.0f ns（Cortex-A9 @ %.0f MHz）' % (A9_NS, A9_MHZ))
    cyc = A9_NS * 1e-9 * A9_MHZ * 1e6
    print('  ⇒ 折合 %.0f 个时钟周期' % cyc)
    print('  ⇒ 摊到 %d 次乘法上，平均每次约 %.1f 个周期'
          % (mul, cyc / mul))
    print()
    print('  ★ 这个数**只是量级上说得通**：A9 的 VFP 单精度乘法大约 4~5 个周期')
    print('    吞吐，加上取数、流水线停顿，折合下来对得上。')
    print('    **但它不是本机实测** —— 本书不把没测过的数当实测值用。')

    # -----------------------------------------------------------------------
    print()
    print('=' * 72)
    print('③ 放进 PL 做流水线：一拍多久 —— 这一步只有一条公式')
    print('=' * 72)
    print('  %-14s %-14s %s' % ('PL 时钟', '一拍', '说明'))
    for f_mhz in (50.0, 100.0, 200.0):
        t_ns = 1000.0 / f_mhz
        print('  %-14s %-14s %s' % ('%.0f MHz' % f_mhz, '%.1f ns' % t_ns,
                                    '流水线满之后，每拍出一个结果'))
    t50 = 1000.0 / 50.0
    print()
    print('  ★ 这是**定义**，不是估计：周期 = 1 / 频率。没有可商量的余地。')

    # -----------------------------------------------------------------------
    print()
    print('=' * 72)
    print('④ ★ 于是文档里那两句话对不上')
    print('=' * 72)
    DOC_NS = 10.0
    print('  文档原文（两处，同一段里）：')
    print('    · 「在 PL 里做成流水线:  ~%d ns (50MHz 时钟, 一拍完成)」' % DOC_NS)
    print('    · 「提升 20×」')
    print()
    print('  可是 50 MHz 的时钟，**一拍就是 %.1f ns**：' % t50)
    print('    %.1f ns/拍 × 50e6 拍/秒 = %.0f ms/秒  ← 这就对上了' % (t50, t50 * 50e6 / 1e6))
    print('    而 %d ns 对应的时钟频率是 %.0f MHz。' % (DOC_NS, 1000.0 / DOC_NS))
    print()
    ratio_doc = A9_NS / DOC_NS
    ratio_ok = A9_NS / t50
    print('  两个可能的加速比：')
    print('    照文档的 %d ns 算：%.0f ns / %d ns = **%.0f×**' % (DOC_NS, A9_NS, DOC_NS, ratio_doc))
    print('    照 50 MHz 实算：  %.0f ns / %.1f ns = **%.0f×**' % (A9_NS, t50, ratio_ok))
    print()
    print('  ★★ 结论：**"50 MHz" 和 "10 ns" 不能同时成立**。')
    print('     要么时钟是 100 MHz（那 10 ns 才对），')
    print('     要么一拍是 20 ns（那加速比就该写 %.0f× 而不是 20×）。' % ratio_ok)
    print()
    print('  ⚠️ 这不是"文档写错了所以不可信"—— 它**量级上完全站得住**')
    print('     （PL 比 CPU 快一个数量级，结论是对的）。')
    print('     但**同一段里的两个数互相推不出来**，说明至少有一个是拍的。')
    print('     本丛书对引用来的数字就是这个态度：接受结论，**重算过程**。')

    # -----------------------------------------------------------------------
    print()
    print('=' * 72)
    print('⑤ 顺带算一个：这个加速到底重不重要')
    print('=' * 72)
    T_US = 1000.0                      # 1 kHz 控制周期
    print('  控制周期 %.0f µs（1 kHz）' % T_US)
    print('  %-24s %-14s %s' % ('实现方式', '占用时间', '占周期比例'))
    for name, ns in (('Cortex-A9 单核算', A9_NS),
                     ('PL 流水线', t50)):
        print('  %-24s %-14s %.3f%%' % (name, '%.0f ns' % ns, 100.0 * ns / 1000.0 / T_US))
    print()
    print('  ★★ 这才是 PL 加速**真正的意义**：不在"快 %.0f 倍"这个数字，' % ratio_ok)
    print('     而在**把 CPU 从这件事里彻底拿出来**。')
    print('     0.02%% 和 0.002%% 都是"微不足道" —— 但前者要占着 CPU 流水线，')
    print('     后者**CPU 完全不参与**，可以专心去跑 EKF。')
    print()
    print('  ⇒ 判断 PL 该不该做的正确问法不是"能快多少倍"，而是')
    print('    「**这件事是不是占住了 CPU / 是不是需要 ns 级确定性**」。')
    print('    满足任一条 ⇒ PL 有戏；都不满足 ⇒ 加速比再高也没必要。')

    print()
    print('=' * 72)
    print('（本脚本只做算术，不做实测。所有"估计"都明确标了是估计。）')
    print('=' * 72)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
