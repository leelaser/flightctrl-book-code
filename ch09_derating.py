# -*- coding: utf-8 -*-
"""ch09_derating.py —— 卷 9 第 4 章：选型要先算判据，再去找取证

## 这一章要讲的事

"选一颗保险丝"看着像选型，其实是**四步推导**：

    ① 算最大持续电流   —— 从功率/电压倒推，而且要拿**最恶劣的输入电压**
    ② 查温度降额       —— 手册给的额定是 25 °C 的，85 °C 要打折
    ③ 反推所需额定     —— 要多少安培的档位才够
    ④ 再核安全关键项   —— 分断能力（短路时能不能断开）

**前三步是算术，第四步是取证。** 本章两样都讲。

## 本脚本做前三步，并顺手抓出一个**真实的口径错误**

二代的设计文档里，最大输入电流写作：

    docs/20（取证文档）：  12.54 A（= 388.7 W / 0.9 / 31 V）
    docs/18（电源规格）：  正确口径：I_in = 388.7 W / 31.0 V（388.7 W 已含效率）

**两条对不上** —— 后者的括注明确说了 388.7 W 是"五路输出 ÷ η0.9"的结果，
**效率已经含在里面了**；前者又除了一次 0.9。

本脚本把两种算法都跑出来，看它们差多少，以及**会不会改变结论**。

跑法：python code/ch09_derating.py
"""

# ---- 工况（来自设计文档的电源规格）----
P_OUT = 349.8          # 五路输出总功率 W
ETA = 0.9              # 电源转换效率
P_IN = 388.7           # 输入功率 W（= P_OUT / ETA，**已含效率**）
V_MIN = 31.0           # 最恶劣输入电压 V（boost 区下限）

# ---- 85 °C 降额系数（来自四家候选的手册降额曲线，逐条量取）----
DERATE = [
    ('候选 A', 0.946),
    ('候选 B', 0.948),
    ('候选 C', 0.948),
    ('候选 D', 0.971),
]

STD_RATINGS = [10, 12, 15, 20, 25, 30]      # 常见额定档位 A


def main():
    print('=' * 74)
    print('① 算最大持续电流 —— 先看两种写法差多少')
    print('=' * 74)
    print('  输入功率 %.1f W（= 输出 %.1f W ÷ 效率 %.1f，**已含效率**）'
          % (P_IN, P_OUT, ETA))
    print('  最恶劣输入电压 %.1f V（宽压输入的 boost 区下限）' % V_MIN)
    print()
    right = P_IN / V_MIN
    wrong = P_IN / ETA / V_MIN
    print('  %-34s = %.2f A   ← 正确：效率已在 388.7 W 里' % ('388.7 W ÷ 31.0 V', right))
    print('  %-34s = %.2f A   ← 又除了一次 0.9' % ('388.7 W ÷ 0.9 ÷ 31.0 V', wrong))
    print()
    print('  ★★ 两条式子相差 **%.0f%%**（%.2f A vs %.2f A）。'
          % ((wrong / right - 1) * 100, right, wrong))
    print('     数字 12.54 是对的，**错的是那个表达式** ——'
          '照着它算会得到 %.2f A。' % wrong)
    print()
    print('  ⇒ 这类错值得单独记一笔：**结论对、过程错**。')
    print('    只核结论的人看不出问题；下一个引用这条式子的人就会被带偏。')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('② 查温度降额 —— 手册的额定是 25 °C 的')
    print('=' * 74)
    print('   四家候选的 85 °C 降额系数（手册降额曲线逐条量取）：')
    print()
    print('  %-10s %-12s %-14s %s' % ('候选', '85 °C 系数', '所需额定值', '该选哪一档'))
    need = []
    for name, k in DERATE:
        req = right / k
        pick = next((r for r in STD_RATINGS if r >= req), None)
        need.append(pick)
        print('  %-10s %-12s %-14s %s'
              % (name, '%.3f' % k, '%.2f A' % req, '%d A' % pick if pick else '—'))
    print()
    print('  ★ 12 A 档够不够？12 × %.3f = %.2f A —— **小于 %.2f A，不够**。'
          % (DERATE[1][1], 12 * DERATE[1][1], right))
    # ★ 把"差多少"也印出来：正文里写"差的是 1.16 A"，
    #   工具不印，那个数就没处核。
    print('    差 %.2f A（%.2f%%）—— 看着像"差一点点"，其实是根本不够。'
          % (right - 12 * DERATE[1][1],
             100 * (right - 12 * DERATE[1][1]) / right))
    print('    ⇒ 四家候选一致地把档位推到 **%d A**。'
          % max(n for n in need if n))
    print('    降额系数 0.948 也就是"额定只能按 **%.1f%%** 用"。'
          % (DERATE[1][1] * 100))
    print()
    print('  ★ 这一步的意义：**降额不是"留点余量"的口号，是一个乘数**。')
    print('    0.948 这个数是从手册曲线上一格一格量出来的 ——')
    print('    **量错 1%，就要在档位上多跨一级。**')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('③ 选大一档的代价与收益')
    print('=' * 74)
    print('  %-12s %-16s %-16s %s' % ('档位', '85 °C 后', '对 12.54 A 的裕量', '评价'))
    for r in (12, 15, 20):
        eff = r * DERATE[1][1]
        margin = (eff - right) / right * 100
        if eff < right:
            verdict = '**不够**'
        elif margin < 20:
            verdict = '刚够'
        else:
            verdict = '裕量充足'
        print('  %-12s %-16s %-16s %s'
              % ('%d A' % r, '%.2f A' % eff, '%+.0f%%' % margin, verdict))
    print()
    print('  ★ 选大一档不是"越保险越好"：额定越大，**短路时动作越慢**，')
    print('    保护的窗口就越窄。所以 ③ 给的是**下限**，不是越大越好。')

    # ------------------------------------------------------------------
    print()
    print('=' * 74)
    print('④ 前三步做完，第四步才轮到"取证"')
    print('=' * 74)
    print('  到这里算出来的只是"**需要 ≥15 A、能耐 85 °C**"。')
    print('  真正决定能不能用的一步在下面，而它**不是算术**：')
    print()
    print('    **分断能力**：短路时这颗器件能不能把电弧断掉。')
    print('    它要拿**电池短路电流**去比 —— 而锂电母线的短路电流可达数百安。')
    print()
    print('  ★★ 所以判据是两级：')
    print('     · **额定电流**决定"平时扛不扛得住"（算术，本脚本已做）')
    print('     · **分断能力**决定"出事时断不断得开"（取证，要查手册 + 估短路电流）')
    print()
    print('    两级都过才算选型成立。而**第二级通常是缺的那一半** ——')
    print('    因为它要求的不是计算能力，是**去核实厂商手册到底写没写**。')

    print()
    print('=' * 74)
    print('口径：功率/电压/降额系数取自二代设计文档的电源规格与手册曲线。')
    print('      本脚本只做算术；分断能力那一级**必须查手册**，不能算。')
    print('=' * 74)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
